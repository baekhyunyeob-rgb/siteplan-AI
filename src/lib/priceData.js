export function getPriceSummaryForPrompt(purpose) {
  const catMap = {
    리모델링: ['지붕', '외벽', '창호', '내부', '설비'],
    농지정리: ['토목'],
    신축: ['토목'],
  }
  const cats = catMap[purpose] ?? catMap['리모델링']
  const lines = [
    '[표준단가 기준: 2025년 상반기 / VAT 별도 / 전국 평균]',
    '[표준품셈 항목은 원가에 이윤·간접비 35% 가산한 견적가 기준]',
  ]
  for (const cat of cats) {
    const items = priceData[cat] ?? []
    if (!items.length) continue
    lines.push(`\n▶ ${cat}`)
    for (const item of items) {
      lines.push(`  - ${item.공종}: ${item.단가.toLocaleString()}원/${item.단위} [${item.출처}, 오차${item.오차}]`)
    }
  }
  lines.push('\n※ 시장조사 항목 ±15~20%, 표준품셈·시장시공가격 항목 ±10%')
  lines.push('※ 인근 지방 중소도시 업체가 수도권 대비 10~20% 유리. 반드시 복수 견적 비교 권장')
  return lines.join('\n')
}
